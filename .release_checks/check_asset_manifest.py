def _mutate_manifest_authority(w: World) -> str:
    """Pick a row that BOTH manifests score and that currently agrees, then break the
    agreement. Mutating a row only one manifest scores (e.g. bev_direct_l3_deeper,
    which the inner manifest leaves numberless) changes the bytes and nothing else --
    a mutation that perturbs the file but not the MEASUREMENT."""
    mans, _ = bookkeeping_files(w)
    if len(mans) == 1:
        # The bundle used to ship two; it now ships one. Inject the historical shape
        # rather than declaring the fault un-injectable -- a selftest that skips
        # itself once the defect is fixed stops guarding the regression.
        rival = ASSETS / "MANIFEST_selftest_rival.txt"
        w.extra[str(rival)] = w.read_text(mans[0])
        mans = bookkeeping_files(w)[0]
        assert len(mans) == 2, "rival manifest was not picked up by discovery"
    parsed = {q: parse_manifest_rows(w, q) for q in mans}
    a, b = mans[0], mans[1]
    cand = [k for k in parsed[a] if k in parsed[b]
            and parsed[a][k] and parsed[b][k] and (parsed[a][k] & parsed[b][k])]
    assert cand, "no row is scored by both manifests and agrees -- nothing to break"
    key = sorted(cand)[0]
    # Edit whichever side has exactly one number, so the sets end up disjoint.
    tgt = a if len(parsed[a][key]) == 1 else b
    if str(tgt) not in w.extra and any(str(q) in w.extra for q in (a, b)):
        tgt = next(q for q in (a, b) if str(q) in w.extra)   # never edit a real file
    lines = w.read_text(tgt).splitlines()
    for i, line in enumerate(lines):
        m = ROW_KEY_RE.match(line.strip())
        if m and m.group(1).rstrip("/") == key:
            for num in MIOU_RE.findall(line):
                line = line.replace(num, "99.99")
            lines[i] = line
            break
    else:
        raise AssertionError(f"could not locate row {key} in {tgt}")
    before = w.read_text(tgt)
    w.text[str(tgt)] = "\n".join(lines)
    assert w.text[str(tgt)] != before, "mutation was a no-op"
    after = parse_manifest_rows(w, tgt)
    assert not (after[key] & parsed[b if tgt is a else a][key]), \
        "mutation left the two rows still overlapping"
    return key


def _mutate_checksums_disagree(w: World) -> str:
    _, cks = bookkeeping_files(w)
    if len(cks) == 1:
        # Rival authority in a SUBDIRECTORY: its entries are relative to its own dir,
        # which is the resolution rule the old checkpoints/checksums.txt exercised.
        auth = cks[0]
        entries = parse_checksums(w, auth)
        tgt = sorted(p for p in entries if str(p).startswith(str(CKPT)))[0]
        rival = CKPT / "checksums_selftest_rival.txt"
        w.extra[str(rival)] = f"{'0' * 64}  {tgt.relative_to(CKPT)}\n"
        cks = bookkeeping_files(w)[1]
        assert len(cks) == 2, "rival checksums file was not picked up by discovery"
        assert tgt in parse_checksums(w, rival), "rival entry did not resolve"
        return str(tgt)
    a, b = cks[0], cks[1]
    shared = sorted(set(parse_checksums(w, a)) & set(parse_checksums(w, b)))
    assert shared, "selftest needs an entry present in both checksums files"
    tgt = shared[0]
    txt = w.read_text(a)
    prev = parse_checksums(w, a)[tgt]
    upd = txt.replace(prev, "0" * 64, 1)
    assert upd != txt, "mutation was a no-op"
    w.text[str(a)] = upd
    return str(tgt)


def _mutate_hide_from_checksums(w: World) -> str:
    _, cks = bookkeeping_files(w)
    auth = authoritative_checksums(w, cks)
    entries = parse_checksums(w, auth)
    # pick a covered file and delete its line: coverage must notice
    tgt = sorted(entries)[0]
    txt = w.read_text(auth)
    new = "\n".join(l for l in txt.splitlines() if entries[tgt] not in l)
    assert new != txt, "mutation was a no-op"
    w.text[str(auth)] = new
    return str(tgt.relative_to(ASSETS))


def _mutate_dangling_entry(w: World) -> str:
    _, cks = bookkeeping_files(w)
    auth = authoritative_checksums(w, cks)
    tgt = sorted(parse_checksums(w, auth))[0]
    before = w.exists(tgt)
    w.hidden.add(str(tgt))
    assert before and not w.exists(tgt), "mutation was a no-op"
    return str(tgt)


def _mutate_bad_hash(w: World) -> str:
    _, cks = bookkeeping_files(w)
    auth = authoritative_checksums(w, cks)
    tgt = sorted(parse_checksums(w, auth))[0]
    real = w.sha256(tgt)
    w.hashes[str(tgt)] = "f" * 64
    assert w.sha256(tgt) != real, "mutation was a no-op"
    return str(tgt)


def _mutate_sha256sum_line(w: World) -> str:
    _, cks = bookkeeping_files(w)
    auth = authoritative_checksums(w, cks)
    entries = parse_checksums(w, auth)
    # smallest covered file: the shadow run still hashes the real bytes of everything
    # else, so pick a target whose corrupted line is unambiguous in the output.
    tgt = min((p for p in entries if p.is_file()), key=lambda p: p.stat().st_size)
    txt = w.read_text(auth)
    new = txt.replace(entries[tgt], "0" * 64, 1)
    assert new != txt, "mutation was a no-op"
    w.text[str(auth)] = new
    # The needle must be the name sha256sum ECHOES, not the absolute path.
    return str(tgt.relative_to(auth.parent))


MUTATIONS = {
    "manifest-single-authority": _mutate_manifest_authority,
    "checksums-single-authority": _mutate_checksums_disagree,
    "every-release-file-has-a-checksum": _mutate_hide_from_checksums,
    "every-checksum-entry-exists": _mutate_dangling_entry,
    "recorded-hash-matches-disk": _mutate_bad_hash,
    "sha256sum--c-exits-zero": _mutate_sha256sum_line,
}


def selftest() -> int:
    """A check that is ALREADY red cannot prove anything by staying red. So the bar is:
    the fault must produce a failure line naming the injected target that the clean
    baseline does not have."""
    missed: List[str] = []
    for name, fn in CHECKS:
        base = set(fn(World()))
        w = World()
        try:
            target = MUTATIONS[name](w)
        except AssertionError as e:
            print(f"  MISSED   {name}   (fault not injectable: {e})")
            missed.append(name)
            continue
        after = set(fn(w))
        new = [d for d in after - base if target in d]
        if new:
            print(f"  TRIPPED  {name}")
        else:
            print(f"  MISSED   {name}   (fault on {target} produced no new failure)")
            missed.append(name)
    n = len(CHECKS)
    if missed:
        print(f"SELFTEST FAILED: {n - len(missed)}/{n} checks provably fail when broken; "
              f"missed: {', '.join(missed)}")
        return 1
    print(f"SELFTEST OK: {n}/{n} checks provably fail when broken")
    return 0


def main() -> int:
    if "--selftest" in sys.argv:
        return selftest()
    w = World()
    failing = 0
    for name, fn in CHECKS:
        bad = fn(w)
        if bad:
            failing += 1
            print(f"  FAIL  {name}   ({bad[0]})")
            for extra in bad[1:6]:
                print(f"        + {extra}")
            if len(bad) > 6:
                print(f"        + ... {len(bad) - 6} more")
        else:
            print(f"  PASS  {name}")
    print(f"{'OK' if not failing else 'FAILED'}: {failing} failing check(s)")
    return 1 if failing else 0


if __name__ == "__main__":
    sys.exit(main())
