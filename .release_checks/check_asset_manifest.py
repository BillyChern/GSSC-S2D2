from typing import Dict, List, Set, Tuple

ASSETS = Path("/workspace/GSSC-S2D2-assets")
CKPT = ASSETS / "checkpoints"

# Scratch. /tmp deadlocks this box; never use it.
TMPDIR = Path(os.environ.get("TMPDIR") or "/workspace/.claude/jobs/d55ebe8b/tmp")

MANIFEST_RE = re.compile(r"^MANIFEST.*\.txt$", re.I)
CHECKSUM_RE = re.compile(r"^(checksums.*\.txt|.*\.sha256)$", re.I)

# A manifest row's key: a checkpoint subdir ('gssc_mf/gssc_31k_mf_step40000/') or a
# flat weight file. Anchored at line start so prose mentioning a path mid-sentence is
# not mistaken for a table row -- the inner manifest's trailing NOTE paragraphs quote
# both 26.1 and 24.3 and would otherwise be parsed as rows.
ROW_KEY_RE = re.compile(
    r"^(?:checkpoints/)?([A-Za-z0-9_]+/[A-Za-z0-9_.-]+/?|[A-Za-z0-9_.]+\.p(?:t|th))\s"
)
# The bundle declares its own release surface in the upload command in README.md:
#   huggingface-cli upload ... checkpoints/ --exclude "*.pt" --exclude "_superseded_*/*"
# Read that instead of hard-coding a belief about which files ship.
EXCLUDE_RE = re.compile(r'--exclude\s+"([^"]+)"')
# mIoU-shaped: two- or one-digit integer part with a decimal. Sizes ('264.9 MB',
# '265_MB') are excluded by requiring the number NOT be followed by a size unit.
MIOU_RE = re.compile(r"(?<![\d.])(\d{1,2}\.\d{1,2})(?!\s*(?:MB|GB|_MB|_GB|%))")


# --------------------------------------------------------------------------- world

class World:
    """All filesystem reads funnel through here so --selftest can perturb the INPUT
    rather than string-replacing a pattern that may have drifted (the classic way a
    selftest goes vacuous: a no-op .replace() against text that no longer matches)."""

    def __init__(self) -> None:
        self.text: Dict[str, str] = {}          # path -> overridden content
        self.extra: Dict[str, str] = {}         # virtual files (content by path)
        self.hidden: Set[str] = set()           # paths to pretend are absent
        self.hashes: Dict[str, str] = {}        # path -> overridden sha256
        self._cache: Dict[Tuple[str, int, int], str] = {}
        self._load_cache()

    # -- cache: hashing 12 GB takes ~9 s; keyed on (path, size, mtime_ns) so an
    # -- edited file is never served stale.
    @property
    def _cache_file(self) -> Path:
        return TMPDIR / "release_checks_sha256.json"

    def _load_cache(self) -> None:
        try:
            raw = json.loads(self._cache_file.read_text())
            self._cache = {tuple(json.loads(k)): v for k, v in raw.items()}  # type: ignore
        except Exception:
            self._cache = {}

    def _save_cache(self) -> None:
        try:
            TMPDIR.mkdir(parents=True, exist_ok=True)
            self._cache_file.write_text(json.dumps(
                {json.dumps(list(k)): v for k, v in self._cache.items()}))
        except OSError:
            pass

    def read_text(self, p: Path) -> str:
        k = str(p)
        if k in self.text:
            return self.text[k]
        if k in self.extra:
            return self.extra[k]
        return p.read_text(errors="replace")

    def exists(self, p: Path) -> bool:
        if str(p) in self.hidden:
            return False
        return p.is_file() or str(p) in self.extra

    def files_under(self, root: Path) -> List[Path]:
        """Regular files under root. followlinks=False: datasets/ is ALL symlinks into
        a 12 GB+ tree and walking it would take minutes and mean nothing."""
        out: List[Path] = []
        for dirpath, _dirs, names in os.walk(root, followlinks=False):
            for n in names:
                p = Path(dirpath) / n
                if p.is_file() and not p.is_symlink() and str(p) not in self.hidden:
                    out.append(p)
        for k in self.extra:
            q = Path(k)
            if str(q.parent).startswith(str(root)) and q not in out:
                out.append(q)
        return sorted(out)

    def sha256(self, p: Path) -> str:
        k = str(p)
        if k in self.hashes:
            return self.hashes[k]
        if k in self.extra:
            return hashlib.sha256(self.extra[k].encode()).hexdigest()
        st = p.stat()
        ck = (k, st.st_size, st.st_mtime_ns)
        if ck in self._cache:
            return self._cache[ck]
        h = hashlib.sha256()
        with open(p, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 22), b""):
                h.update(chunk)
        self._cache[ck] = h.hexdigest()
        self._save_cache()
        return self._cache[ck]


# ----------------------------------------------------------------------- discovery

def bookkeeping_files(w: World) -> Tuple[List[Path], List[Path]]:
    mans, cks = [], []
    for p in w.files_under(ASSETS):
        if MANIFEST_RE.match(p.name):
            mans.append(p)
        elif CHECKSUM_RE.match(p.name):
            cks.append(p)
    return mans, cks


def parse_checksums(w: World, path: Path) -> Dict[Path, str]:
    """-> {absolute target: recorded hash}. Entries are relative to the file's OWN
    directory, which is exactly how sha256sum -c resolves them; getting this wrong
    would make the inner file look like it covered nothing."""
    out: Dict[Path, str] = {}
    for line in w.read_text(path).splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) != 2 or not re.fullmatch(r"[0-9a-f]{64}", parts[0]):
            continue
        target = parts[1].lstrip("*").strip()
        out[(path.parent / target).resolve()] = parts[0]
    return out


def manifest_dirs(w: World) -> Set[str]:
    """Checkpoint directories the bundle's own manifest enumerates, relative to
    checkpoints/. A file inside one of these is part of the release by the bundle's
    own account, so no exclusion pattern may exempt it from checksum coverage."""
    out: Set[str] = set()
    for m in bookkeeping_files(w)[0]:
        for key in parse_manifest_rows(w, m):
            if (CKPT / key).is_dir():
                out.add(key)
    return out


def release_surface(w: World) -> Tuple[List[Path], List[Path]]:
    """(files that must carry a checksum, files the bundle declares local-only)."""
    pats: List[str] = []
    readme = ASSETS / "README.md"
    if w.exists(readme):
        for line in w.read_text(readme).splitlines():
            if "checkpoints/" in line:
                pats += EXCLUDE_RE.findall(line)
    listed = manifest_dirs(w)
    must, local = [], []
    for p in w.files_under(CKPT):
        rel = p.relative_to(CKPT)
        inside_listed = any(str(rel).startswith(d + "/") for d in listed)
        # A '_'-prefixed path component is the bundle's quarantine convention
        # (pyramid/_superseded_20260820/). Kept separate from the declared patterns
        # so that losing the --exclude line cannot silently widen the exemption.
        quarantined = any(part.startswith("_") for part in rel.parts[:-1])
        excluded = quarantined or any(
            fnmatch.fnmatch(str(rel), pat) or fnmatch.fnmatch(rel.name, pat)
            for pat in pats)
        (local if (excluded and not inside_listed) else must).append(p)
    return must, local


def parse_manifest_rows(w: World, path: Path) -> Dict[str, Set[str]]:
    """-> {normalised checkpoint key: set of mIoU-shaped numbers on its row}."""
    rows: Dict[str, Set[str]] = {}
    for line in w.read_text(path).splitlines():
        m = ROW_KEY_RE.match(line.strip())
        if not m:
            continue
        key = m.group(1).rstrip("/")
        rows.setdefault(key, set()).update(MIOU_RE.findall(line))
    return rows


def authoritative_checksums(w: World, cks: List[Path]) -> Path:
    """The one with the widest coverage of checkpoints/ -- derived, not named, so
    renaming the file does not silently blind the gate."""
    disk = set(w.files_under(CKPT))
    return max(cks, key=lambda p: len(disk & set(parse_checksums(w, p))))


# -------------------------------------------------------------------------- checks

def a1_manifest_authority(w: World) -> List[str]:
    mans, _ = bookkeeping_files(w)
    if not mans:
        return [f"{ASSETS}: no MANIFEST*.txt found at all -- the gate has nothing to read"]
    if len(mans) == 1:
        return []
    bad: List[str] = []
    parsed = {p: parse_manifest_rows(w, p) for p in mans}
    base, *rest = mans
    for other in rest:
        a, b = parsed[base], parsed[other]
        for key in sorted(set(a) | set(b)):
            if key not in a:
                bad.append(f"{other}: lists '{key}' which {base.name} at "
                           f"{base} does not -- two manifests, two inventories")
            elif key not in b:
                bad.append(f"{base}: lists '{key}' which {other} does not")
            elif a[key] and b[key] and not (a[key] & b[key]):
                # DISJOINT, not merely unequal. One manifest legitimately carries extra
                # context numbers on the same row (a rounded value, a delta); demanding
                # set equality would manufacture a disagreement out of that.
                bad.append(f"'{key}': {base} says mIoU {sorted(a[key])} but "
                           f"{other} says {sorted(b[key])} -- no value in common")
    if not bad:
        bad.append(f"{len(mans)} manifests ship ({', '.join(str(p) for p in mans)}) and "
                   f"they happen to agree, but nothing marks which is authoritative")
    return bad


def a2_checksums_authority(w: World) -> List[str]:
    _, cks = bookkeeping_files(w)
    if not cks:
        return [f"{ASSETS}: no checksums file found at all"]
    if len(cks) == 1:
        return []
    bad: List[str] = []
    parsed = {p: parse_checksums(w, p) for p in cks}
    for i, p in enumerate(cks):
        for q in cks[i + 1:]:
            for tgt in sorted(set(parsed[p]) & set(parsed[q])):
                if parsed[p][tgt] != parsed[q][tgt]:
                    bad.append(f"{tgt}: {p} records {parsed[p][tgt][:12]}..., "
                               f"{q} records {parsed[q][tgt][:12]}...")
    # SCOPE disagreement. Hash-equality alone calls a 14-of-65 subset 'consistent';
    # but running that file exits 0 while 51 files go unverified, so a partial
    # authority sitting next to a fuller one is itself the defect.
    auth = authoritative_checksums(w, cks)
    for p in cks:
        if p.resolve() == auth.resolve():
            continue        # the widest-coverage file is the intended authority; a3
                            # measures ITS coverage. Only the RIVALS are the defect here.
        subtree = set(w.files_under(p.parent)) - {p.resolve()}
        covered = set(parsed[p])
        missed = subtree - covered
        if missed and len(covered) < len(subtree):
            bad.append(f"{p}: covers {len(covered & subtree)}/{len(subtree)} files under "
                       f"{p.parent} yet verifies clean -- a second, narrower authority "
                       f"(first uncovered: {sorted(missed)[0]})")
    return bad


def a3_disk_covered(w: World) -> List[str]:
    _, cks = bookkeeping_files(w)
    if not cks:
        return [f"{ASSETS}: no checksums file; every file under {CKPT} is unverified"]
    auth = authoritative_checksums(w, cks)
    recorded = set(parse_checksums(w, auth))
    must, local = release_surface(w)
    disk = [p for p in must if p.resolve() != auth.resolve()]
    if not disk:
        # BLIND-GUARD: an --exclude pattern wide enough to exempt the whole bundle
        # would let this check pass by measuring nothing.
        return [f"{ASSETS}/README.md: the declared --exclude patterns exempt every "
                f"file under {CKPT}; checksum coverage is unmeasurable"]
    missing = [p for p in disk if p.resolve() not in recorded]
    if not missing:
        return []
    # One line PER uncovered file: an aggregate line whose offender list is truncated
    # cannot be matched by name, and a gate whose detail cannot be matched cannot be
    # selftested. The count goes first so the progress signal is still one glance.
    out = [f"{auth}: {len(missing)}/{len(disk)} release files under {CKPT} carry no "
           f"checksum entry ({len(local)} more are declared local-only and exempt)"]
    out += [f"{auth}: no checksum entry for {p.relative_to(ASSETS)}" for p in missing]
    return out


def a4_entries_exist(w: World) -> List[str]:
    _, cks = bookkeeping_files(w)
    bad: List[str] = []
    for p in cks:
        for tgt in sorted(parse_checksums(w, p)):
            if not w.exists(tgt):
                bad.append(f"{p}: entry '{tgt}' does not exist on disk")
    return bad[:8]


def a5_hashes_match(w: World) -> List[str]:
    _, cks = bookkeeping_files(w)
    bad: List[str] = []
    for p in cks:
        for tgt, rec in sorted(parse_checksums(w, p).items()):
            if not w.exists(tgt):
                continue                      # a4 owns that failure
            got = w.sha256(tgt)
            if got != rec:
                bad.append(f"{p}: '{tgt}' recorded {rec[:12]}... but computes "
                           f"{got[:12]}... -- the recorded hash is stale")
    return bad


def _run_sha256sum(directory: Path, name: str) -> Tuple[int, str]:
    r = subprocess.run(["sha256sum", "-c", "--quiet", name], cwd=str(directory),
                       capture_output=True, text=True)
    return r.returncode, (r.stdout + r.stderr).strip()


def a6_verification_exits_zero(w: World) -> List[str]:
    """The reproducer's actual command. Kept separate from a5 because our parser and
    GNU coreutils can disagree (binary '*' prefix, backslash-escaped names, BOM) and
    a gate that only trusts its own parser cannot see that."""
    _, cks = bookkeeping_files(w)
    bad: List[str] = []
    for p in cks:
        d, name = p.parent, p.name
        if str(p) in w.text or str(p) in w.extra:   # selftest: verify a perturbed copy
            shadow = Path(tempfile.mkdtemp(prefix="ckshadow_", dir=TMPDIR))
            (shadow / name).write_text(w.read_text(p))
            for child in d.iterdir():         # symlinks: hash the REAL bytes, no copy
                if child.name != name:
                    (shadow / child.name).symlink_to(child)
            d, name = shadow, name
        rc, out = _run_sha256sum(d, name)
        if rc == 0:
            continue
        # Emit one line PER failing entry. Reporting only out.splitlines()[0] made the
        # gate unable to distinguish a new fault from the pre-existing stale entry --
        # and made its own selftest vacuous, which is how the bug was found.
        entries = [l for l in out.splitlines() if l.endswith(": FAILED")]
        for e in entries[:8]:
            bad.append(f"`cd {d} && sha256sum -c {name}` exits {rc}: {e}")
        if not entries:
            bad.append(f"`cd {d} && sha256sum -c {name}` exits {rc}: "
                       f"{out.splitlines()[0] if out else '(no output)'}")
    return bad


CHECKS = [
    ("manifest-single-authority", a1_manifest_authority),
    ("checksums-single-authority", a2_checksums_authority),
    ("every-release-file-has-a-checksum", a3_disk_covered),
    ("every-checksum-entry-exists", a4_entries_exist),
    ("recorded-hash-matches-disk", a5_hashes_match),
    ("sha256sum--c-exits-zero", a6_verification_exits_zero),
]


